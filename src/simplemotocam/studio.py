def export_python(state):
    """Embed the same validated numerical implementation, not a different approximation."""
    state = validate_state(state)
    source = Path(studio_engine.__file__).read_text(encoding="utf-8")
    source = (
        Path(studio_compiled.__file__).read_text(encoding="utf-8")
        + "\n"
        + re.sub(r"from \.(?:studio_compiled|studio_backend) import [^\n]*# EXPORT_(?:COMPILED|VISION)", "",
                 Path(studio_runtime.__file__).read_text(encoding="utf-8"))
        + "\n"
        + re.sub(
            r"from \.studio_runtime import [\s\S]*?# EXPORT_RUNTIME",
            "",
            source,
            count=1,
        )
    )
    source = (
        "OPENCV24_CUSTOM_SOURCE = "
        + repr(Path(studio_backend.__file__).read_text(encoding="utf-8"))
        + "\n"
        + "OPENCV24_EXPORT_HINT = "
        + repr(str(studio_backend.opencv24_worker()))
        + "\n"
        + Path(studio_backend.__file__).read_text(encoding="utf-8")
        + "\n"
        + re.sub(
            r"from \.studio_backend import [\s\S]*?# EXPORT_BACKEND",
            "",
            source,
            count=1,
        )
    )
    license_text = (ROOT / "LICENSE").read_text(encoding="utf-8")
    runner = """

STATE = json.loads(STATE_JSON)

def main():
    import argparse
    parser=argparse.ArgumentParser(description='Exported SimpleOpenCV algorithm; requires numpy and opencv-python.')
    inputs=parser.add_mutually_exclusive_group()
    inputs.add_argument('--camera',type=int)
    inputs.add_argument('--video')
    inputs.add_argument('--image')
    parser.add_argument('--frames',type=int,default=120)
    parser.add_argument('--show',action='store_true')
    args=parser.parse_args()
    if args.frames<1: parser.error('--frames must be positive')
    pipeline=StudioPipeline(STATE)
    cap=None
    still=None
    if args.image:
        still=cv2.imread(args.image,cv2.IMREAD_COLOR)
        if still is None: raise RuntimeError('Cannot read image')
    elif args.camera is not None or args.video:
        cap=cv2.VideoCapture(args.camera if args.camera is not None else args.video)
        if not cap.isOpened(): cap.release(); raise RuntimeError('Cannot open source')
    elif STATE['source']['type']!='synthetic':
        parser.error('Supply --camera, --video or --image explicitly for this saved source.')
    processed=0
    try:
        for index in range(args.frames):
            if cap is not None:
                ok,image=cap.read()
                if not ok: break
            else: image=still if still is not None else demo_frame(index)
            values,ready=pipeline.process(image)
            result=values[STATE['view']['result']]
            processed+=1
            if args.show:
                cv2.imshow('SimpleOpenCV export',display_plane(result,gain=STATE['view']['gain']))
                if cv2.waitKey(30)&255 in (27,ord('q')): break
        if not processed: raise RuntimeError('Source produced no frames')
        print(json.dumps({'frames':processed,'result':STATE['view']['result'],
                          'min':float(result.min()),'max':float(result.max())}))
    finally:
        if cap is not None: cap.release()
        if args.show: cv2.destroyAllWindows()

if __name__=='__main__': main()
"""
    return (
        "# Generated by SimpleOpenCV Studio. MIT license; see project LICENSE.\n"
        "# Numerical engine and configuration are embedded. Camera access is explicit.\n"
        + "\n".join("# " + line for line in license_text.splitlines())
        + "\n"
        + source
        + "\nSTATE_JSON = "
        + repr(json.dumps(state, ensure_ascii=False))
        + "\n"
        + runner
    )


def encoded_image(image):
    ok, data = cv2.imencode(".jpg", image, [cv2.IMWRITE_JPEG_QUALITY, 85])
    if not ok:
        raise ValueError("Could not encode preview")
    return "data:image/jpeg;base64," + base64.b64encode(data).decode("ascii")


class StudioSession:
    def __init__(self, storage, backend=None):
        self.storage = Path(storage)
        self.storage.mkdir(parents=True, exist_ok=True)
        (self.storage / "projects").mkdir(exist_ok=True)
        (self.storage / "uploads").mkdir(exist_ok=True)
        self.lock = threading.RLock()
        initial = default_state()
        initial["backend"] = {
            "id": backend or os.environ.get("SIMPLEMOTOCAM_DEFAULT_BACKEND", "opencv24")
        }
        self.state = validate_state(initial)
        self.pipeline = StudioPipeline(self.state)
        self.revision = 0
        self.index = 0
        self.capture = None
        self.still = None
        self.code_authorized = False

    def close(self):
        if self.capture is not None:
            self.capture.release()
        self.capture = None
        self.still = None
        self.pipeline.previous = None

    def configure(self, state):
        valid = validate_state(state)
        if (
            valid["source"]["type"] in ("image", "video")
            and not (self.storage / "uploads" / valid["source"]["asset"]).is_file()
        ):
            raise ValueError(
                "Source file is not present on this computer; import it again"
            )
        # Validate and exercise the graph before replacing the last working state.
        pipeline = StudioPipeline(valid)
        if not any(n["kind"] == "custom" for n in valid["nodes"]):
            pipeline.process(demo_frame(0, 160, 120))
            pipeline.process(demo_frame(1, 160, 120))
        if valid["nodes"] != self.state["nodes"] or valid.get(
            "backend"
        ) != self.state.get("backend"):
            self.code_authorized = False
        pipeline.previous = None
        if valid["source"] != self.state["source"]:
            self.close()
            self.index = 0
        if (
            valid["source"] == self.state["source"]
            and valid["nodes"] == self.state["nodes"]
            and valid.get("backend") == self.state.get("backend")
        ):
            self.pipeline.state = valid
        else:
            self.pipeline = pipeline
        self.state = valid
        self.revision += 1
        return {"state": self.state, "revision": self.revision}

    def frame(self, run_code=False):
        has_code = any(
            n["kind"] == "custom" and n["enabled"] and n["params"]["code"].strip()
            for n in self.state["nodes"]
        )
        if has_code and not self.code_authorized:
            if run_code is not True:
                return {"needsCodeRun": True, "revision": self.revision}
            self.code_authorized = True
        start = time.perf_counter()
        source = self.state["source"]
        if source["type"] == "synthetic":
            image = demo_frame(self.index)
        elif source["type"] == "image":
            if self.still is None:
                self.still = cv2.imread(
                    str(self.storage / "uploads" / source["asset"]), cv2.IMREAD_COLOR
                )
                if self.still is None:
                    raise ValueError("Cannot decode image")
            image = self.still
        else:
            if self.capture is None:
                value = (
                    source["camera"]
                    if source["type"] == "camera"
                    else str(self.storage / "uploads" / source["asset"])
                )
                self.capture = cv2.VideoCapture(value)
                if not self.capture.isOpened():
                    self.close()
                    raise ValueError(
                        "Cannot open camera/video. Check access and camera index."
                    )
            ok, image = self.capture.read()
            if not ok:
                self.close()
                return {
                    "ended": True,
                    "revision": self.revision,
                    "message": (
                        "Video ended"
                        if source["type"] == "video"
                        else "Camera stopped delivering frames"
                    ),
                }
        # Bound live work; exported algorithms retain original input dimensions.
        height, width = image.shape[:2]
        if max(height, width) > 960:
            image = cv2.resize(
                image,
                (
                    round(width * 960 / max(height, width)),
                    round(height * 960 / max(height, width)),
                ),
                interpolation=cv2.INTER_AREA,
            )
        values, ready = self.pipeline.process(image)
        self.index += 1
        view = self.state["view"]
        stats = {
            name: {
                "min": float(v.min()),
                "max": float(v.max()),
                "mean": float(v.mean(dtype=np.float64)),
            }
            for name, v in values.items()
        }
        images = {
            "camera": encoded_image(image),
            "signal": encoded_image(
                display_plane(values[view["signal"]], view["signed"], view["gain"])
            ),
            "result": encoded_image(
                display_plane(values[view["result"]], False, view["gain"])
            ),
        }
        return {
            "images": images,
            "backend": self.state["backend"],
            "stats": stats,
            "ready": ready,
            "frame": self.index,
            "revision": self.revision,
            "size": [image.shape[1], image.shape[0]],
            "originalSize": [width, height],
            "processingMs": round((time.perf_counter() - start) * 1000, 2),
        }

    def save(self, state):
        valid = validate_state(state)
        slug = (
            "".join(c if c.isalnum() else "-" for c in valid["name"]).strip("-")[:40]
            or "project"
        )
        identifier = f'{slug}-{datetime.now(timezone.utc).strftime("%Y%m%dT%H%M%S")}-{secrets.token_hex(3)}'
        record = {"savedAt": datetime.now(timezone.utc).isoformat(), "state": valid}
        with (self.storage / "projects" / f"{identifier}.json").open(
            "x", encoding="utf-8"
        ) as f:
            json.dump(record, f, ensure_ascii=False, indent=2)
        return {"id": identifier, "savedAt": record["savedAt"], "state": valid}

    def projects(self):
        items = []
        for path in (self.storage / "projects").glob("*.json"):
            try:
                data = json.loads(path.read_text(encoding="utf-8"))
                items.append(
                    {
                        "id": path.stem,
                        "name": data["state"]["name"],
                        "savedAt": data["savedAt"],
                    }
                )
            except (ValueError, KeyError, OSError):
                continue
        return sorted(items, key=lambda x: x["savedAt"], reverse=True)


class StudioServer(ThreadingHTTPServer):
    daemon_threads = True

    def __init__(self, address, session):
        super().__init__(address, StudioHandler)
        self.session = session
        self.token = secrets.token_urlsafe(32)

    def server_close(self):
        self.session.close()
        super().server_close()


class StudioHandler(BaseHTTPRequestHandler):
    def log_message(self, *args):
        pass

    def send(
        self,
        status,
        data,
        content_type="application/json; charset=utf-8",
        filename=None,
    ):
        if not isinstance(data, bytes):
            data = json.dumps(data, ensure_ascii=False, allow_nan=False).encode("utf-8")
        self.send_response(status)
        self.send_header("Content-Type", content_type)
        self.send_header("Content-Length", str(len(data)))
        self.send_header("Cache-Control", "no-store")
        self.send_header("X-Content-Type-Options", "nosniff")
        self.send_header(
            "Content-Security-Policy",
            "default-src 'self'; img-src 'self' data:; style-src 'self' 'unsafe-inline'; script-src 'self'; frame-src 'self'; connect-src 'self'; object-src 'none'; base-uri 'none'; frame-ancestors 'self'",
        )
        if filename:
            self.send_header(
                "Content-Disposition", f'attachment; filename="{filename}"'
            )
        self.end_headers()
        try:
            self.wfile.write(data)
        except (BrokenPipeError, ConnectionResetError):
            pass

    def local_request(self):
        port = self.server.server_address[1]
        allowed = {f"127.0.0.1:{port}", f"localhost:{port}"}
        if self.headers.get("Host") not in allowed:
            return False
        origin = self.headers.get("Origin")
        return not origin or origin in {f"http://{h}" for h in allowed}

    def do_GET(self):
        if not self.local_request():
            return self.send(403, {"error": "Local requests only"})
        path = unquote(urlparse(self.path).path)
        session = self.server.session
        try:
            if path == "/api/bootstrap":
                with session.lock:
                    return self.send(
                        200,
                        {
                            "token": self.server.token,
                            "state": session.state,
                            "revision": session.revision,
                            "blocks": KINDS,
                            "catalog": library_catalog(session.storage),
                            "projects": session.projects(),
                        },
                    )
            if path == "/api/library":
                with session.lock:
                    return self.send(200, library_catalog(session.storage))
            if path == "/api/projects":
                with session.lock:
                    return self.send(200, session.projects())
            if path.startswith("/api/projects/"):
                name = path.rsplit("/", 1)[1]
                if not name or any(c in name for c in "/\\."):
                    raise ValueError("Invalid project ID")
                target = session.storage / "projects" / f"{name}.json"
                if not target.is_file():
                    return self.send(404, {"error": "Project not found"})
                return self.send(200, json.loads(target.read_text(encoding="utf-8")))
            if path.startswith("/manuals/"):
                root = MANUALS.resolve()
                relative = path[len("/manuals/") :]
            else:
                root = UI.resolve()
                relative = "index.html" if path == "/" else path.lstrip("/")
            target = (root / relative).resolve()
            if not target.is_relative_to(root) or not target.is_file():
                return self.send(404, {"error": "File not found"})
            return self.send(
                200,
                target.read_bytes(),
                mimetypes.guess_type(target.name)[0] or "application/octet-stream",
            )
        except (ValueError, OSError) as exc:
            return self.send(400, {"error": str(exc)})

    def do_POST(self):
        if not self.local_request() or not secrets.compare_digest(
            self.headers.get("X-Studio-Token", ""), self.server.token
        ):
            return self.send(403, {"error": "Invalid session token"})
        path = urlparse(self.path).path
        try:
            length = int(self.headers.get("Content-Length", "0"))
            limit = 100 * 1024 * 1024 if path == "/api/upload" else 256 * 1024
            if length <= 0 or length > limit:
                return self.send(413, {"error": f"Request limit: {limit} bytes"})
            raw = self.rfile.read(length)
            session = self.server.session
            with session.lock:
                if path == "/api/upload":
                    extension = self.headers.get("X-File-Extension", "").lower()
                    if extension not in (
                        ".png",
                        ".jpg",
                        ".jpeg",
                        ".bmp",
                        ".webp",
                        ".avi",
                        ".mp4",
                        ".mov",
                        ".mkv",
                    ):
                        raise ValueError("Unsupported image/video extension")
                    identifier = hashlib.sha256(raw).hexdigest()[:24] + extension
                    target = session.storage / "uploads" / identifier
                    if not target.exists():
                        with target.open("xb") as f:
                            f.write(raw)
                    return self.send(
                        200,
                        {
                            "asset": identifier,
                            "type": (
                                "image"
                                if extension
                                in (".png", ".jpg", ".jpeg", ".bmp", ".webp")
                                else "video"
                            ),
                        },
                    )
                data = json.loads(raw)
                if path == "/api/config":
                    return self.send(200, session.configure(data))
                if path == "/api/frame":
                    return self.send(200, session.frame(data.get("runCode", False)))
                if path == "/api/stop":
                    session.close()
                    return self.send(200, {"stopped": True})
                if path == "/api/library/save":
                    return self.send(200, save_library_block(session.storage, data))
                if path == "/api/save":
                    return self.send(200, session.save(data))
                if path == "/api/export":
                    return self.send(
                        200,
                        export_python(data).encode("utf-8"),
                        "text/x-python; charset=utf-8",
                        "simplemotocam_algorithm.py",
                    )
                return self.send(404, {"error": "Unknown action"})
        except (
            ValueError,
            TypeError,
            KeyError,
            RecursionError,
            cv2.error,
            OSError,
        ) as exc:
            return self.send(400, {"error": str(exc)})


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--port", type=int, default=8765)
    parser.add_argument("--no-browser", action="store_true")
    parser.add_argument("--storage", type=Path, default=ROOT / ".motocam")
    parser.add_argument("--backend", choices=("opencv24", "current"), default=None)
    args = parser.parse_args(argv)
    try:
        session = StudioSession(args.storage, backend=args.backend)
    except ValueError as exc:
        parser.exit(
            1,
            str(exc)
            + "\nInstall the OpenCV 2.4 worker or explicitly use --backend current.\n",
        )
    try:
        server = StudioServer(("127.0.0.1", args.port), session)
    except OSError as exc:
        parser.exit(1, f"Cannot start local studio: {exc}\nTry --port 8766.\n")
    url = f"http://127.0.0.1:{server.server_address[1]}"
    print(f"SimpleOpenCV Studio: {url}", flush=True)
    print(
        "Stop with Ctrl+C. Camera access begins only after Run/Step with Camera selected.",
        flush=True,
    )
    if not args.no_browser:
        webbrowser.open(url)
    try:
        server.serve_forever()
    except KeyboardInterrupt:
        pass
    finally:
        server.server_close()


if __name__ == "__main__":
    main()
